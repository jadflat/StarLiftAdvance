#!/usr/bin/env python3
"""Build Star Lift GBA FS: python gba/build.py  ->  gba/out/STARLIFT.gba

The game is this project's own copy, game/ (merged up to CHStarlift 0.24; CHStarlift itself stays the CHGame
version). Its CHStarlift/CHStarlift.ino, Card.cpp, Synth.cpp and the vendored CHGame library are compiled with
zig c++ for the ARM7TDMI, next to the GBA back end in gba/src (display, input, sound, card, save). STARLIFT.DAT is
appended to the ROM and read from there as the "SD card". A copy of the library is made in gba/build/lib so that the one
header that decides where hot code lives (chgame/RamFunc.h) can be swapped for the GBA's, leaving chgame/ untouched.
"""
import os, shutil, struct, subprocess, sys
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent / "game"           # the game, this project's copy
SKETCH = ROOT / "CHStarlift"
LIBS = ROOT / "chgame/platform/board/arduino/CHGame/libraries"
DAT = ROOT / "dist/STARLIFT.DAT"
BUILD = Path(os.environ.get("GBA_BUILD", HERE / "build"))   # separate folders let two builds run side by side
OUT = Path(os.environ.get("GBA_OUT", HERE / "out"))
VERSION = "0.8"                      # Star Lift GBA FS, shown on the title screen

TARGET = ["-target", "arm-linux-musleabi", "-mcpu=arm7tdmi"]
COMMON = ["-target", "thumb-linux-musleabi", "-mcpu=arm7tdmi"] + ["-std=gnu++17", "-O2", "-w", "-fno-exceptions", "-fno-rtti", "-fno-threadsafe-statics", "-fno-pic",
                   "-ffunction-sections", "-fdata-sections", "-ffreestanding", "-mlong-calls", "-fno-builtin-printf",
                   "-DCHSIM", "-DCH32X035", "-DARDUINO=10800", "-DCHGAME_DEBUG=0", "-DCHGBA=1",
                   "-DGFX_W=240", "-DGFX_H=160"]          # Star Lift GBA FS: the GBA's whole screen
ARM_IWRAM = {"Synth.cpp", "sketch.cpp", "CHGfx_draw.cpp"}      # keep in step with the EXCLUDE_FILE list in src/gba.ld
ARM_RAMFUNC = '-DRAMFUNC(name)=__attribute__((section(".iwram.text"), noinline, target("arm")))'   # (inc/chgame/RamFunc.h's, in ARM)
WRAPS = ["_ZN5synth5musicEi", "_ZN5synth3sfxERKN5audio6EffectE", "_ZN5synth6loadedEv"]


def run(cmd):
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode:
        sys.stderr.write(" ".join(map(str, cmd[:6])) + " ...\n" + r.stdout + r.stderr)
        raise SystemExit(1)
    return r.stdout


def snapshot():
    """A copy of game/ (without its build output), with its card regenerated by tools/make_card.py in the copy, so the
    card and CardIndex.h always match the code being built."""
    d = BUILD / "head"
    if d.exists():
        shutil.rmtree(d)
    shutil.copytree(ROOT, d, ignore=shutil.ignore_patterns("out", "build", "__pycache__"))
    run(["python", "-c", "import os,runpy;os.chdir(r'%s');runpy.run_path('tools/make_card.py', run_name='__main__')" % d])
    return d / "CHStarlift", d / "out/card/STARLIFT.DAT"


def apply_patches(gen):
    """gba/patches/NN-name.patch, in order: GBA-only changes to the generated copy of the game (gen/sketch.cpp ...),
    never to CHStarlift/ itself. Each hunk is

        @@ <file in gen>
        <<<<<<<
        text that must appear exactly once
        =======
        its replacement
        >>>>>>>

    Lines starting with # outside a hunk are comments. A hunk whose text is missing or not unique stops the build: the
    game changed under the patch, which has to be looked at again. Other files in gba/patches (.inc) are copied into gen
    for the patches to #include."""
    pdir = HERE / "patches"
    for f in sorted(pdir.iterdir()):
        if f.suffix != ".patch":
            shutil.copy(f, gen / f.name)
    only = os.environ.get("GBA_PATCHES")                    # e.g. GBA_PATCHES=01,02: just those (measuring one at a time)
    for f in sorted(pdir.glob("*.patch")):
        if only and f.name[:2] not in only.split(","):
            print(f"patch {f.name}: skipped (GBA_PATCHES)")
            continue
        lines =f.read_text(encoding="utf-8").split("\n")
        i, n = 0, 0
        while i < len(lines):
            if not lines[i].startswith("@@ "):
                if lines[i].strip() and not lines[i].startswith("#"):
                    raise SystemExit(f"PATCH FAILED: {f.name}:{i + 1}: expected '@@ <file>' or a # comment")
                i += 1
                continue
            target, at = gen / lines[i][3:].strip(), i + 1
            try:
                a, m, b = lines.index("<<<<<<<", i), lines.index("=======", i), lines.index(">>>>>>>", i)
            except ValueError:
                raise SystemExit(f"PATCH FAILED: {f.name}:{at}: an unfinished hunk")
            if not a == i + 1 < m < b:
                raise SystemExit(f"PATCH FAILED: {f.name}:{at}: a malformed hunk")
            old, new = "\n".join(lines[a + 1:m]) + "\n", "\n".join(lines[m + 1:b]) + "\n"
            text = target.read_text(encoding="utf-8")
            k = text.count(old)
            if k != 1:
                raise SystemExit(f"PATCH FAILED: {f.name}:{at}: the text to replace is in {target.name} {k} times, not once"
                                 f" (the game changed: look at the patch again)\n{old}")
            target.write_text(text.replace(old, new), newline="\n")
            i, n = b + 1, n + 1
        print(f"patch {f.name}: {n} hunks")


def prepare_lib():
    lib = BUILD / "lib"
    if lib.exists():
        shutil.rmtree(lib)
    for n in ("CHGfx", "CHGame", "CHSd"):
        shutil.copytree(LIBS / n / "src", lib / n)
    shutil.copy(HERE / "inc/chgame/RamFunc.h", lib / "CHGame/chgame/RamFunc.h")
    return lib


def main():
    BUILD.mkdir(exist_ok=True); OUT.mkdir(exist_ok=True)
    lib = prepare_lib()
    game, datf = snapshot()
    dat = datf.read_bytes()
    nblocks = (len(dat) + 511) // 512
    gen = BUILD / "gen"
    gen.mkdir(exist_ok=True)
    (gen / "rom_info.cpp").write_text(
        "#include <stdint.h>\nextern \"C\" const uint32_t gba_datBlocks = %d;\n"
        "extern \"C\" const char gba_saveTag[] __attribute__((used, section(\".rodata.savetag\"))) = \"SRAM_V113\";\n" % nblocks,
        newline="\n")
    # the .ino as C++
    ino = gen / "sketch.cpp"
    src = (game / "CHStarlift.ino").read_text(encoding="utf-8")
    if "-DGBA_PROF" in os.environ.get("GBA_CFLAGS", ""):   # the game's dbg::prof sections, timed (main.cpp gba_prof*)
        src = ('extern "C" void gba_profStart(); extern "C" void gba_prof(unsigned char);\n'
               + src.replace("dbg::profStart()", "gba_profStart()").replace("dbg::prof(", "gba_prof("))
    ino.write_text(src, newline="\n")
    shutil.copy(game / "Synth.cpp", gen / "Synth.cpp")   # copied too, so that patches can reach it (10-synth-blocks)
    if "--nopatch" not in sys.argv:    # --nopatch: the game as it is, for comparing pictures and timings
        apply_patches(gen)

    inc = [HERE / "inc", lib / "CHGfx", lib / "CHGame", lib / "CHSd", game]
    flags = COMMON + [f"-I{d}" for d in inc] + [f"-DGBA_VERSION=\"{VERSION}\""]
    if os.environ.get("GBA_SCENECHECK"):   # patch 01's check build: old and new scenery drawn and compared every frame
        flags += ["-DGBA_SCENECHECK=1"]
    flags += os.environ.get("GBA_CFLAGS", "").split()      # experiments: extra -D switches for every file
    srcs = [ino, gen / "rom_info.cpp", game / "Card.cpp", gen / "Synth.cpp"]
    srcs += sorted((HERE / "src").glob("*.cpp"))
    srcs += sorted(p for p in (lib / "CHGfx").glob("*.cpp") if p.name != "CHGfx.cpp")
    srcs += sorted(p for p in (lib / "CHGame/chgame").glob("*.cpp") if p.name != "Save.cpp")
    objdir = BUILD / "obj"
    objdir.mkdir(exist_ok=True)

    def cc(src):
        o = objdir / (src.stem + ".o")
        if src.name == "sketch.cpp" and os.environ.get("GBA_SKETCH_THUMB"):
            # GBA_SKETCH_THUMB=1: the game's cartridge code as Thumb (half the fetches), its hot functions ARM in IWRAM.
            # Not the default here: Thumb has no long multiply, so every division (even by a constant) is a call, and at
            # 240x160 that cost more than Thumb saved (42.6 ms a frame against 37.7 all ARM, the same 3000 frames).
            run(["zig", "c++"] + flags + ["-O3", "-funroll-loops", ARM_RAMFUNC, "-c", str(src), "-o", str(o)])
        elif src.name in ARM_IWRAM:      # hot files: ARM state, linked into IWRAM (gba.ld)
            run(["zig", "c++"] + flags + ["-target", "arm-linux-musleabi", "-O3", "-funroll-loops", "-c", str(src), "-o", str(o)])
        else:
            run(["zig", "c++"] + flags + ["-c", str(src), "-o", str(o)])
        return o

    def asm(src):
        o = objdir / (src.stem + ".o")
        run(["zig", "cc"] + TARGET + ["-marm", "-c", str(src), "-o", str(o)])
        return o

    with ThreadPoolExecutor(8) as ex:
        objs = list(ex.map(cc, srcs)) + [asm(HERE / "src/crt0.S"), asm(HERE / "src/div.S")]
    elf = OUT / "STARLIFT.elf"
    ld = HERE / "src/gba.ld"
    if os.environ.get("GBA_SCENECHECK"):   # no room in IWRAM for both: the game's own scenery loops run from ROM there
        cols = (".text._ZL7colPairPhiiPKhS1_S1_S1_ .text._ZL7colFillPhhhi .text._ZL6colTexPhhiiiPKhS1_ "
                ".text._ZL14drawGroundColsv .text._ZL13drawLayerColsi")
        t = ld.read_text()
        assert cols in t, "gba.ld changed: update the check build's list"
        ld = BUILD / "gba_check.ld"
        ld.write_text(t.replace(cols, ""), newline="\n")
    link = ["zig", "c++"] + TARGET + ["-nostdlib", "-static", f"-Wl,-T,{ld}",
            "-Wl,--gc-sections"]
    link += [f"-Wl,--wrap={w}" for w in WRAPS]
    run(link + [str(o) for o in objs] + ["-o", str(elf)])
    binf = OUT / "image.bin"
    run(["zig", "objcopy", "-O", "binary", str(elf), str(binf)])
    img = bytearray(binf.read_bytes())
    code = len(img)
    img += b"\xff" * (-len(img) % 512)
    rom = bytearray(img) + dat
    rom += b"\xff" * (-len(rom) % 4)
    fix_header(rom)
    rom_path = OUT / "STARLIFT.gba"
    rom_path.write_bytes(rom)
    (OUT / f"STARLIFT_FS{VERSION.replace('.', '_')}.gba").write_bytes(rom)   # a copy named for the version
    print(f"image {code} B (code + constants + IWRAM image), card {len(dat)} B, ROM {len(rom)} B -> {rom_path}")
    report(elf)


def report(elf):
    d = elf.read_bytes()
    shoff, = struct.unpack_from("<I", d, 0x20)
    shentsize, shnum, shstrndx = struct.unpack_from("<HHH", d, 0x2E)
    secs = [struct.unpack_from("<IIIIIIIIII", d, shoff + i * shentsize) for i in range(shnum)]
    stroff = secs[shstrndx][4]
    for s in secs:
        name = d[stroff + s[0]:d.index(bytes([0]), stroff + s[0])].decode()
        if name in (".text", ".iwram", ".bss", ".ewram", ".init_array"):
            print("  %-12s addr %08x  %6d B" % (name, s[3], s[5]))


# The 156-byte boot logo at 0x04 is Nintendo's, so it is not kept in this
# repository. The build takes it from gba/logo.bin (not tracked: copy it from
# any GBA ROM's bytes 0x04-0x9F) or from GBA_LOGO; without it the ROM still
# runs in emulators, and real hardware wants it fixed with gbafix.
def load_logo():
    p = Path(os.environ.get("GBA_LOGO", Path(__file__).parent / "logo.bin"))
    if p.is_file():
        logo = p.read_bytes()[:156]
        assert len(logo) == 156, "%s: needs 156 bytes" % p
        return logo
    print("  no gba/logo.bin: header logo left empty (emulators only; use gbafix for hardware)")
    return bytes(156)


def fix_header(rom):
    rom[4:4 + 156] = load_logo()
    title = b"STARLIFT".ljust(12, b"\0")
    rom[0xA0:0xAC] = title
    rom[0xAC:0xB0] = b"CHSL"
    rom[0xB0:0xB2] = b"JF"
    rom[0xB2] = 0x96
    rom[0xB3] = 0
    rom[0xB4] = 0
    rom[0xBC] = 0
    rom[0xBD] = (-(sum(rom[0xA0:0xBD]) + 0x19)) & 0xFF


if __name__ == "__main__":
    main()
