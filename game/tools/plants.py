def frames(rows):
    """The plant, and the plant swaying: its upper half shifted a pixel right (a rock does not sway)."""
    w = max(len(r) for r in rows) + 1
    a = [r.ljust(w, '.') for r in rows]
    b = []
    for y, r in enumerate(a):
        b.append(('.' + r[:-1]) if y < len(a) // 2 else r)
    return a, b
